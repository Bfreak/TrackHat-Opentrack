#!/usr/bin/env python3
"""Generates tracker-neuralnet/facemesh_canonical.h from MediaPipe's canonical face model.

Inputs (Apache 2.0, https://github.com/google-ai-edge/mediapipe, mediapipe/modules/face_geometry/data/):
    canonical_face_model.obj
    geometry_pipeline_metadata_landmarks.pbtxt

Usage: make-facemesh-canonical.py <canonical_face_model.obj> <geometry_pipeline_metadata_landmarks.pbtxt> <out.h>
"""
import re
import sys

obj, pbtxt, out = sys.argv[1:4]
verts = [tuple(map(float, line.split()[1:4])) for line in open(obj) if line.startswith("v ")]
assert len(verts) == 468
weights = [(int(i), float(w)) for i, w in re.findall(r"landmark_id:\s*(\d+)\s*weight:\s*([\d.]+)", open(pbtxt).read())]
assert len(weights) == 33

with open(out, "w") as f:
    f.write("""// Generated by scripts/trackhat/make-facemesh-canonical.py. Do not edit.
//
// Canonical face model and Procrustes landmark weights from MediaPipe
// (mediapipe/modules/face_geometry/data), Copyright 2020 The MediaPipe Authors,
// licensed under the Apache License, Version 2.0.
//
// The vertices are converted from MediaPipe's frame (x right, y up, z towards the viewer)
// to the tracker's image frame (x right, y down, z into the image). Units are centimeters.

#pragma once

namespace neuralnet_tracker_ns::facemesh_canonical
{

inline constexpr int num_vertices = 468;

inline constexpr float vertices[num_vertices][3] = {
""")
    for x, y, z in verts:
        f.write("    { %.6ff, %.6ff, %.6ff },\n" % (x, -y, -z))
    f.write("""};

struct weighted_landmark
{
    int index;
    float weight;
};

inline constexpr int num_weights = 33;

inline constexpr weighted_landmark weights[num_weights] = {
""")
    for i, w in weights:
        f.write("    { %d, %.9ff },\n" % (i, w))
    f.write("""};

} // namespace neuralnet_tracker_ns::facemesh_canonical
""")
